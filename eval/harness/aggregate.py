#!/usr/bin/env python3
"""Roll up every graded trial in eval/results/runs/*.json into eval/leaderboard.md.

This is the single running artifact: one row per (task, harness, model,
effort), aggregated across every trial that has ever been run, each linking
to its full per-trial report. Never hand-edit leaderboard.md -- re-run this
script after every new trial is graded.

Usage:
    python eval/harness/aggregate.py
"""
import glob
import json
import os
import statistics
import subprocess
import sys


def repo_root():
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                          capture_output=True, text=True, check=True)
    return out.stdout.strip()


def load_records(root):
    records = []
    for path in sorted(glob.glob(os.path.join(root, "eval", "results", "runs", "*.json"))):
        with open(path) as f:
            records.append(json.load(f))
    return records


def fmt_pct(x):
    return f"{x*100:.0f}%" if isinstance(x, (int, float)) else "--"


def main():
    root = repo_root()
    records = load_records(root)
    out_path = os.path.join(root, "eval", "leaderboard.md")
    if not records:
        # Still (re)write the file rather than leave stale rows behind --
        # e.g. after every prior run was archived out of eval/results/runs/.
        with open(out_path, "w") as f:
            f.write("# Leaderboard\n\nGenerated by `eval/harness/aggregate.py` "
                     "from every graded trial in `eval/results/runs/`. Do not "
                     "hand-edit -- re-run the script instead.\n\nNo graded "
                     "trials yet.\n")
        print(f"[aggregate] no graded trials found -- wrote empty {out_path}")
        return 0

    by_task_model = {}
    for r in records:
        # harness+effort included: a same-model run under a different harness
        # or effort is a different experiment, not more trials of this one --
        # collapsing them previously mixed cohorts silently.
        key = (r["task_id"], r["harness"], r["model"], r.get("effort"))
        by_task_model.setdefault(key, []).append(r)

    rows = []
    for (task_id, harness, model, effort), trials in by_task_model.items():
        scores = [t["total_score"] for t in trials if t.get("total_score") is not None]
        mean = round(statistics.mean(scores), 1) if scores else None
        best = max(scores) if scores else None
        worst = min(scores) if scores else None
        latest = sorted(trials, key=lambda t: t["run_id"])[-1]
        mean_corr = _mean_cat(trials, "correctness")
        mean_test = _mean_cat(trials, "test_adequacy")
        mean_scope = _mean_cat(trials, "scope_discipline")
        rows.append({
            "task_id": task_id, "harness": harness, "model": model, "effort": effort,
            "n": len(trials), "mean": mean, "best": best, "worst": worst,
            "correctness": mean_corr, "test_adequacy": mean_test, "scope": mean_scope,
            "latest_report": f"results/reports/{latest['run_id']}.md",
        })

    rows.sort(key=lambda r: (r["task_id"], -(r["mean"] or -1)))

    lines = [
        "# Leaderboard",
        "",
        "Generated by `eval/harness/aggregate.py` from every graded trial in "
        "`eval/results/runs/`. Do not hand-edit -- re-run the script instead.",
        "",
        f"Total graded trials: {len(records)} across {len(by_task_model)} (task, harness, model, effort) groups.",
        "",
    ]

    current_task = None
    for r in rows:
        if r["task_id"] != current_task:
            current_task = r["task_id"]
            lines += [f"## Task: `{current_task}`", "",
                      "| Model | Harness | Effort | Trials | Mean | Best | Worst | Correctness | Test adequacy | Scope | Latest report |",
                      "|---|---|---|---|---|---|---|---|---|---|---|"]
        lines.append(
            f"| `{r['model']}` | {r['harness']} | {r['effort'] or '--'} | {r['n']} | {r['mean']} | {r['best']} | {r['worst']} | "
            f"{fmt_pct(r['correctness'])} | {fmt_pct(r['test_adequacy'])} | {fmt_pct(r['scope'])} | "
            f"[report]({r['latest_report']}) |"
        )
        lines.append("")

    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"[aggregate] wrote {out_path} ({len(rows)} rows from {len(records)} trials)")
    return 0


def _mean_cat(trials, cat_id):
    vals = [t["category_scores"].get(cat_id) for t in trials
            if isinstance(t.get("category_scores", {}).get(cat_id), (int, float))]
    return round(statistics.mean(vals), 2) if vals else None


if __name__ == "__main__":
    sys.exit(main())
